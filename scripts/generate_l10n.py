"""Compile the complete Italian/English UI catalogs; reject missing keys/parameters."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'lib/l10n'
data={lang:json.loads((root/f'app_{lang}.json').read_text()) for lang in ['it','en']}
assert data['it'].keys()==data['en'].keys(), 'Catalog keys differ'
for key,it in data['it'].items():
 en=data['en'][key]
 assert it==key and isinstance(en,str) and en, key
 assert set(re.findall(r'\{p\d+\}',it))==set(re.findall(r'\{p\d+\}',en)),key
# JSON object/string syntax is also Dart syntax; escape interpolation markers.
text=json.dumps(data,ensure_ascii=False,indent=2).replace('$',r'\$')
(root/'catalog.g.dart').write_text('// GENERATED by scripts/generate_l10n.py; edit the JSON catalogs.\n// SPDX-License-Identifier: BSD-3-Clause\nconst cieMessages = <String, Map<String, String>>'+text+';\n')
print(f'Compiled {len(data["it"])} messages for Italian and English.')
