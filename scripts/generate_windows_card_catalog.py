"""Verify official Windows registration data and generate its fixed C++ table."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--upstream-file', type=Path, help='Pinned official StoreProvider.cpp; verify all ATRs/masks offline')
p.add_argument('--check', action='store_true')
a = p.parse_args()
catalog = json.loads((ROOT / 'packaging/windows/card-catalog.json').read_text())
if a.upstream_file:
    source = a.upstream_file.read_bytes()
    assert hashlib.sha256(source).hexdigest() == catalog['sourceSha256'], 'Official source hash differs'
    text = source.decode('utf-8-sig')
    arrays = {name: bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', value))
              for name, value in re.findall(r'BYTE\s+(ATR\w*)\[\]\s*=\s*\{([^}]+)\}', text)}
    official = [{'id': name, 'atr': arrays[atr].hex(),
                 'mask': (b'\xff' * len(arrays[atr]) if mask == 'nullptr' else arrays[mask]).hex()}
                for name, atr, mask in re.findall(r'RegisterCard\(hSC,\s*"(CIE_\d+)",\s*(ATR\d*),\s*sizeof\(ATR\d*\),\s*(\w+)\)', text)]
    assert official == catalog['registrations'], 'Catalog differs from official registration calls'
assert len(catalog['registrations']) == 12
lines = ['// Generated by scripts/generate_windows_card_catalog.py; do not edit.',
         '// ATR/Mask facts from IPZS cie-middleware ' + catalog['commit'] + '.',
         '// Original BSD-3-Clause attribution is retained with the runtime notices.',
         '#pragma once', '#include <cstdint>', '#include <vector>', 'namespace cie_setup {',
         'struct CardPattern {const wchar_t* id;std::vector<uint8_t> atr,mask;};',
         'inline const std::vector<CardPattern> cardCatalog{']
for row in catalog['registrations']:
    atr, mask = bytes.fromhex(row['atr']), bytes.fromhex(row['mask'])
    assert 0 < len(atr) == len(mask) <= 36
    assert all((v & m) == v for v, m in zip(atr, mask))
    arr = lambda value: '{' + ','.join('0x%02x' % b for b in value) + '}'
    lines.append(' {L"' + row['id'] + '",' + arr(atr) + ',' + arr(mask) + '},')
lines += ['};', '}']
generated = '\n'.join(lines) + '\n'
target = ROOT / 'native/platform/windows/web/card_catalog.h'
if a.check:
    assert target.read_text(encoding='utf-8') == generated, 'Regenerate card_catalog.h'
else:
    target.write_text(generated, encoding='utf-8')
print('12 official ATR/mask registrations verified' if a.upstream_file else '12 catalog entries generated/checked')
